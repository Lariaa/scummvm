#ifndef DIRECTOR_LINGO_XTRAS_CAST_FONTXTRA_H
#define DIRECTOR_LINGO_XTRAS_CAST_FONTXTRA_H

#include "common/str.h"

#include "director/castmember/castmember.h"

namespace Director {

class XtraCastMember;

namespace FontXtra {

CastMember *createCastMember(Cast *cast, uint16 castId, XtraCastMember *xtra);

} // End of namespace FontXtra

// "Font" Asset Xtra cast member (D7+). It shows nothing: it carries a font the
// movie's own text is set in, so that the text looks the same on a machine
// that has never heard of it. The glyphs hang off the member as an 'XMED'
// child in Bitstream's Portable Font Resource format, which is what
// "Font Xtra.x32" rasterises -- the string "Private data generated by Bitstream
// TrueDoc (TM)" sits in that Xtra in the clear.
//
// TKKG 7, 9, 11, 13 and 14 and Loewenzahn 6 all ship one or more.
class FontXtraCastMember : public CastMember {
public:
	FontXtraCastMember(Cast *cast, uint16 castId, XtraCastMember &source);
	FontXtraCastMember(Cast *cast, uint16 castId, FontXtraCastMember &source);

	CastMember *duplicate(Cast *cast, uint16 castId) override { return (CastMember *)(new FontXtraCastMember(cast, castId, *this)); }

	void load() override;

	// Nothing ever shows this member, so the cast has to load it itself.
	bool loadsWithTheCast() const override { return true; }

	Common::String formatInfo() override;

	// The name the document's style runs use to ask for this font
	Common::String _fontName;
	// The id the font manager handed out for it, -1 until load() ran
	int _fontId = -1;
	// Whether the payload was a font the manager could be given
	bool _registered = false;
};

} // End of namespace Director

#endif
